def hex_to_rgb(h):
    h = h.lstrip("#")
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))


def main():
    with open(PATH, encoding="utf-8") as f:
        items = json.load(f)

    out = []
    for item in items:
        name, pinyin = item["name"], item["pinyin"]
        if name in RENAMES:
            name, pinyin = RENAMES[name]
        hex_value = item["hex"].upper()
        r, g, b = hex_to_rgb(hex_value)
        entry = {
            "pinyin": pinyin,
            "name": name,
            "hex": hex_value,
            "rgb": f"{r}, {g}, {b}",
        }
        entry.update(NOTES.get(name, {}))
        out.append(entry)

    unknown = [n for n in NOTES if n not in {e["name"] for e in out}]
    if unknown:
        raise SystemExit(f"NOTES 中有不存在的颜色：{unknown}")

    with open(PATH, "w", encoding="utf-8") as f:
        f.write("[\n")
        f.write(",\n".join("  " + json.dumps(e, ensure_ascii=False) for e in out))
        f.write("\n]\n")
    print(f"完成：{len(out)} 个颜色，其中 {sum(1 for e in out if e['name'] in NOTES)} 个带补充内容")


if __name__ == "__main__":
    main()
